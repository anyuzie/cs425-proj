"""Confidence-weighted z-space distance versus the dot product and cosine.

Usage (repository root):
    python -m recommender.experiments.weighted_distance

``weighted_distance@kappa3_v1`` scores
-sum_t w_t (3 u_t - z_t)^2 over observed types, using the tracker's slot weight
w_t. Cosine discards magnitude (one observed type ties every same-sign
occupation at 1) and the dot product rewards a large z on one type regardless
of fit. Hypothesis: distance beats cosine most where the profile is sparse
(three or fewer observed types), and beats the dot product overall. Primary
metric: MRR, in the <=3-observed subgroup against cosine (the live default);
NDCG@10, Hit@5 and Recall@10 are secondary. Dot product and cosine run
unchanged on the same sessions and must reproduce extractor_inputs_v1.

Inputs: Tier 2 extractor sessions (one opening turn, real DeBERTa extractor and
decay tracker), format 3 (with slot weights). The subgroup is defined from the
observed-type count, which a live system can see; no hidden slots are used.
"""
import argparse
import json
from pathlib import Path
import random
import statistics

from .compare import paired_comparison
from .evaluate import digest, run, save_json
from .evaluation import METRICS

SESSIONS = Path("data/eval/extractor_sessions_dev_v3")
ROOT = Path("reports/ranking/weighted_distance_v1")
CONFIGS = {"dot": Path("configs/ranking/baseline_v1.json"), "cosine": Path("configs/ranking/m1_cosine.json"),
           "distance": Path("configs/ranking/m1_weighted_distance.json")}
PRIMARY = ("mrr", "ndcg_at_10", "hit_at_5", "recall_at_10")
SPARSE_MAX = 3
SUBGROUPS = ("sparse_le3", "dense_ge4")


def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def lines(path):
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line.strip()]


def subgroups(sessions):
    return {s["id"]: "sparse_le3" if len(s["turns"][-1]["observed_types"]) <= SPARSE_MAX else "dense_ge4"
            for s in sessions}


def subgroup_effects(diffs, groups, *, samples=2000, seed=425):
    """Mean treatment-minus-control difference per subgroup, with a paired bootstrap 95% CI."""
    result = {}
    for name in SUBGROUPS:
        rows = [d for d in diffs if groups[d["profile_id"]] == name]
        rng = random.Random(seed)
        entry = {"profiles": len(rows)}
        for m in PRIMARY:
            values = [r[m] for r in rows]
            means = sorted(statistics.mean(rng.choices(values, k=len(values))) for _ in range(samples)) if values else []
            entry[m] = {"mean_difference": statistics.mean(values) if values else None,
                        "ci95": [means[int(.025 * (samples - 1))], means[int(.975 * (samples - 1))]] if values else None,
                        "improved": sum(v > 0 for v in values), "regressed": sum(v < 0 for v in values)}
        result[name] = entry
    return result


def subgroup_metrics(directory, groups):
    rows = load(Path(directory) / "per_profile.json")
    return {name: {m: statistics.mean(r[m] for r in rows if groups[r["profile_id"]] == name) for m in PRIMARY}
            for name in SUBGROUPS}


def cell(value):
    return f"{value['mean_difference']:+.4f} [{value['ci95'][0]:+.4f}, {value['ci95'][1]:+.4f}]"


def write_report(summary):
    counts = summary["subgroup_counts"]
    out = ["# Confidence-weighted z-space distance, v1 (Tier 2)", "",
           "Generated by `python -m recommender.experiments.weighted_distance` from saved artifacts.", "",
           "## Hypothesis (fixed before running)", "", summary["hypothesis"], "",
           "## Inputs", "",
           f"Tier 2 extractor sessions `{SESSIONS.as_posix()}` (120 development profiles, one opening turn, real "
           "extractor and decay tracker), replayed from the saved v2 readings to add slot weights; vectors and "
           "observed types are identical to v2. Subgroups by observed-type count: "
           f"<=3 observed {counts['sparse_le3']}, >=4 observed {counts['dense_ge4']}.", "",
           "## Ten permanent M2 metrics (all 120 profiles)", "",
           "| Run | no-signal profiles | " + " | ".join(METRICS) + " |", "|---|---:|" + "---:|" * len(METRICS)]
    for name, item in summary["metrics"].items():
        out.append(f"| {name} | {summary['no_signal'][name]} | " + " | ".join(f"{item[m]:.6f}" for m in METRICS) + " |")
    out += ["", "## Metrics by subgroup", "", "| Run | subgroup | " + " | ".join(PRIMARY) + " |",
            "|---|---|" + "---:|" * len(PRIMARY)]
    for name, groups in summary["subgroup_metrics"].items():
        for group, values in groups.items():
            out.append(f"| {name} | {group} | " + " | ".join(f"{values[m]:.4f}" for m in PRIMARY) + " |")
    out += ["", "## Paired differences, distance minus control (95% paired bootstrap CI)", "",
            "| Control | profiles | " + " | ".join(PRIMARY) + " | improved / regressed (MRR) |",
            "|---|---|" + "---:|" * (len(PRIMARY) + 1)]
    for control, result in summary["comparisons"].items():
        m = result["metrics"]
        out.append(f"| {control} | all {result['profiles']} | " + " | ".join(cell(m[k]) for k in PRIMARY)
                   + f" | {m['mrr']['improved']} / {m['mrr']['regressed']} |")
        for group, values in summary["subgroups"][control].items():
            out.append(f"| {control} | {group} {values['profiles']} | " + " | ".join(cell(values[k]) for k in PRIMARY)
                       + f" | {values['mrr']['improved']} / {values['mrr']['regressed']} |")
    out += ["", "## Limitations", "",
            "- One opening turn per profile; the slot weight is then roughly the extractor confidence, so the "
            "evidence-mass benefit that accumulates over a dialogue is not exercised here (Tier 3 is needed).",
            "- kappa=3 comes from the mock tracker's z/3 mapping, not from fitting; it was not tuned.",
            "- 120 synthetic development profiles with LLM-written texts; CIs describe this set only. "
            "Subgroup CIs are wide (n~50/70). Defaults are unchanged by this report.",
            "- The <=3 subgroup is selected by observed count (visible live), so it can gate a decision, "
            "but it also correlates with shorter or vaguer openings.", ""]
    (ROOT / "README.md").write_text("\n".join(out), encoding="utf-8")


def main():
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    if (ROOT / "run_summary.json").exists():
        raise ValueError(f"{ROOT} already holds a completed experiment; choose a new version")
    manifest = load(SESSIONS / "manifest.json")
    for name, expected in manifest["outputs_sha256"].items():
        if digest(SESSIONS / name) != expected:
            raise ValueError(f"Session file changed after building: {name}")
    ROOT.mkdir(parents=True, exist_ok=True)
    evaluation = ROOT / "evaluation_actual_tracker.json"
    if not evaluation.exists():
        save_json(evaluation, {**load("configs/m2.json"), "run_id": "m2_extractor_tracker_dev_v3",
                               "input_mode": "actual_tracker", "profiles": (SESSIONS / "sessions.jsonl").as_posix()})
    history = ROOT / "evaluation_history.csv"
    groups = subgroups(lines(SESSIONS / "sessions.jsonl"))
    summary = {"hypothesis": " ".join(__doc__.split("\n\n")[2:3]).replace("\n", " "), "sessions_manifest": manifest,
               "subgroup_counts": {g: list(groups.values()).count(g) for g in SUBGROUPS},
               "metrics": {}, "no_signal": {}, "subgroup_metrics": {}, "comparisons": {}, "subgroups": {}}
    for name, path in CONFIGS.items():
        print(f"RUN {name}", flush=True)
        summary["metrics"][name] = run(evaluation, ROOT / name, history=history, ranking_config=path)
        summary["no_signal"][name] = sum(r["status"] != "ranked" for r in load(ROOT / name / "per_profile.json"))
        summary["subgroup_metrics"][name] = subgroup_metrics(ROOT / name, groups)
    for control in ("dot", "cosine"):
        result, diffs = paired_comparison(ROOT / control, ROOT / "distance")
        save_json(ROOT / f"comparison_distance_vs_{control}.json", result)
        save_json(ROOT / f"paired_diffs_distance_vs_{control}.json", diffs)
        summary["comparisons"][control] = result
        summary["subgroups"][control] = subgroup_effects(diffs, groups)
    reference = load("reports/ranking/extractor_inputs_v1/run_summary.json")["metrics"]
    for name in ("dot", "cosine"):
        if any(abs(summary["metrics"][name][m] - reference[f"extractor_{name}"][m]) > 1e-12 for m in METRICS):
            raise ValueError(f"{name} control no longer reproduces extractor_inputs_v1")
    summary["controls_reproduce_extractor_inputs_v1"] = True
    write_report(summary)
    save_json(ROOT / "run_summary.json", summary)
    print(json.dumps({n: {m: round(v[m], 4) for m in PRIMARY} for n, v in summary["metrics"].items()}, indent=2))
    print(f"Report: {ROOT / 'README.md'}")


if __name__ == "__main__":
    main()
