"""Run the four frozen sentence-to-task treatments and derive their performance measures.

Usage (repository root):  python -m recommender.experiments.clause_tasks

Outputs go to reports/ranking/clause_tasks_v1/. The run refuses to overwrite a
completed experiment. All ten permanent M2 metrics come from the unchanged
evaluator; the extra diagnostics below are derived from saved per-profile
results and never feed back into scoring.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import statistics

from .compare import paired_comparison
from .evaluate import run, save_json
from .evaluation import METRICS
from .history import dataset_fingerprint
from ..semantic import clause_tasks as treatment_module
from ..semantic.clause_tasks import CONFIGURATIONS, configure_local_models, sentence_sign, split_sentences

ROOT = Path("reports/ranking/clause_tasks_v1")
CSV_PATH = Path("reports/ranking/semantic_experiments_consolidated.csv")
CONTEXT_TASKS = Path("reports/ranking/context_tasks_v1")
BASE = {"components": {"m1": {"algorithm": "weighted_dot_product", "variant": "baseline_v1"},
                       "m3": None, "m4": None}, "fusion": None}
# Each treatment's single-variable control besides the dot product.
COUNTERPARTS = {
    "minilm_groups10": ("context_tasks_v1", CONTEXT_TASKS / "minilm_groups10"),
    "mpnet_groups10": ("context_tasks_v1", CONTEXT_TASKS / "mpnet_groups10"),
    "minilm_groups10_signed": ("unsigned", ROOT / "minilm_groups10"),
    "mpnet_groups10_signed": ("unsigned", ROOT / "mpnet_groups10"),
}
BLOCK = 10


def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def reranker_diagnostics(control_rows, treatment_rows):
    """Measures that isolate the reranker from the fixed first stage.

    Groups of 10 keep membership, so only targets ranked 1-10 by the dot product
    can reach the top 5 (the Hit@5 ceiling), and only targets inside the top 100
    can move at all. Within-block position is 1..10; random ordering expects 5.5.
    """
    control = {r["profile_id"]: r for r in control_rows}
    rows = []
    for row in treatment_rows:
        before, after = control[row["profile_id"]]["target_rank"], row["target_rank"]
        if before is not None and before <= 100:
            rows.append((before, after))
    first_block = [(b, a) for b, a in rows if b <= BLOCK]
    position = lambda rank: (rank - 1) % BLOCK + 1
    return {
        "profiles": len(treatment_rows),
        "targets_in_reranked_top100": len(rows),
        "hit_at_5_ceiling": len(first_block) / len(treatment_rows),
        "first_block_top5_conversion": (sum(a <= 5 for _, a in first_block) / len(first_block)) if first_block else None,
        "first_block_top1_conversion": (sum(a == 1 for _, a in first_block) / len(first_block)) if first_block else None,
        "mean_within_block_position": statistics.mean(position(a) for _, a in rows) if rows else None,
        "random_within_block_position": (BLOCK + 1) / 2,
        "target_moved_up": sum(a < b for b, a in rows),
        "target_moved_down": sum(a > b for b, a in rows),
        "target_unchanged": sum(a == b for b, a in rows),
        "mean_rank_change": statistics.mean(b - a for b, a in rows) if rows else None,
        "definition": "Computed from saved per-profile target ranks; positive mean_rank_change = moved up.",
    }


def sentence_diagnostics(inputs, policy):
    counts, negatives = [], 0
    for snapshot in inputs:
        sentences = split_sentences(snapshot["user_sentences"])
        counts.append(len(sentences))
        negatives += sum(sentence_sign(s, policy) == -1 for s in sentences)
    return {"mean_sentences_per_profile": statistics.mean(counts), "min_sentences": min(counts),
            "max_sentences": max(counts), "explicit_negative_sentences": negatives,
            "profiles_without_sentences": sum(c == 0 for c in counts)}


def fmt(value, signed=False):
    if value is None:
        return "n/a"
    return f"{value:+.6f}" if signed else f"{value:.6f}"


def write_report(summary):
    metric_header = "| Experiment | " + " | ".join(METRICS) + " |\n|---|" + "---:|" * len(METRICS) + "\n"
    lines = ["# Sentence-to-task nearest-neighbour reranking, v1", "",
             "Generated by `python -m recommender.experiments.clause_tasks`; numbers are copied from saved artifacts.", "",
             "## Hypothesis", "", summary["hypothesis"], "",
             "## Ten permanent M2 metrics (120 development/oracle profiles, 378 occupations)", "", metric_header.rstrip("\n")]
    for name, metrics in summary["metrics"].items():
        lines.append(f"| {name} | " + " | ".join(fmt(metrics[m]) for m in METRICS) + " |")
    lines += ["", "## Paired differences (treatment minus control, 95% bootstrap CI, 2,000 resamples, seed 425)", "",
              "| Treatment | Control | Hit@5 | MRR | NDCG@10 | improved / regressed profiles (MRR) |", "|---|---|---:|---:|---:|---:|"]
    for item in summary["comparisons"]:
        m = item["summary"]["metrics"]
        cell = lambda k: f"{m[k]['mean_difference']:+.6f} [{m[k]['ci95'][0]:+.6f}, {m[k]['ci95'][1]:+.6f}]"
        lines.append(f"| {item['treatment']} | {item['control']} | {cell('hit_at_5')} | {cell('mrr')} | "
                     f"{cell('ndcg_at_10')} | {m['mrr']['improved']} / {m['mrr']['regressed']} |")
    lines += ["", "## Reranker diagnostics", "",
              "Groups of 10 preserve membership, so the dot product fixes which targets *can* reach the top 5. "
              "These measures isolate how well the second stage orders what it is given.", "",
              "| Experiment | Hit@5 ceiling | first-block top-5 conversion | first-block top-1 conversion | "
              "mean within-block position (random 5.5) | moved up / down / same | mean rank change |",
              "|---|---:|---:|---:|---:|---:|---:|"]
    for name, d in summary["diagnostics"].items():
        lines.append(f"| {name} | {fmt(d['hit_at_5_ceiling'])} | {fmt(d['first_block_top5_conversion'])} | "
                     f"{fmt(d['first_block_top1_conversion'])} | {fmt(d['mean_within_block_position'])} | "
                     f"{d['target_moved_up']} / {d['target_moved_down']} / {d['target_unchanged']} | "
                     f"{fmt(d['mean_rank_change'], True)} |")
    lines += ["", "## Query sentences", "", "```json", json.dumps(summary["sentences"], indent=2), "```", "",
              "## Latency", "", "| Experiment | median s | p95 s |", "|---|---:|---:|"]
    for name, latency in summary["latency"].items():
        lines.append(f"| {name} | {latency['preloaded_rank_median_seconds']:.4f} | {latency['preloaded_rank_p95_seconds']:.4f} |")
    lines += ["", "## Limitations", "",
              "- Development/oracle profiles only; synthetic text, oracle RIASEC values. Not real-user or tracker evidence.",
              "- Selecting the best of four treatments is not independent validation; CIs are descriptive.",
              "- The preference rule is conservative and lexical; mixed or complex dislikes stay unsigned.",
              "- Cosine similarity measures topical association, not suitability. Defaults are unchanged.", ""]
    (ROOT / "README.md").write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--no-csv", action="store_true", help="Do not append rows to the consolidated CSV")
    args = parser.parse_args()
    if (ROOT / "run_summary.json").exists():
        raise ValueError(f"{ROOT} already holds a completed experiment; choose a new version")
    models = configure_local_models()
    original = CSV_PATH.read_bytes()
    with CSV_PATH.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        fields, old = reader.fieldnames, list(reader)
    if any(r["experiment"].endswith("__clause_tasks_v1") for r in old):
        raise ValueError("Clause-task rows already appended; choose a new experiment version")
    ROOT.mkdir(parents=True, exist_ok=True)
    history = ROOT / "evaluation_history.csv"

    control = ROOT / "weighted_dot_product_control"
    baseline = run(output=control, history=history, ranking_config=BASE)
    reference = next(r for r in old if r["experiment"] == "weighted_dot_product")
    if any(abs(baseline[k] - float(reference[k])) > 1e-12 for k in METRICS):
        raise ValueError("Dot-product control no longer reproduces the recorded metrics")
    control_manifest = load(control / "manifest.json")
    control_rows = load(control / "per_profile.json")
    inputs = load(control / "inputs.json")

    summary = {"hypothesis": " ".join(treatment_module.__doc__.split("\n\n")[1:3]).replace("\n", " "),
               "model_paths": models, "metrics": {"weighted_dot_product": baseline},
               "diagnostics": {"weighted_dot_product": reranker_diagnostics(control_rows, control_rows)},
               "comparisons": [], "latency": {}, "sentences": {}, "rows": []}
    for name in ("minilm_groups10", "mpnet_groups10"):  # saved chunk-mean controls, not rerun
        directory = CONTEXT_TASKS / name
        if directory.is_dir():
            label = f"{name}__context_tasks_v1 (saved)"
            summary["metrics"][label] = load(directory / "metrics.json")
            summary["diagnostics"][label] = reranker_diagnostics(control_rows, load(directory / "per_profile.json"))

    for name, parameters in CONFIGURATIONS.items():
        config_path = Path("configs/ranking") / f"clause_tasks_{name}_v1.json"
        if config_path.exists():
            if load(config_path) != {**BASE, "reranking": parameters}:
                raise ValueError(f"{config_path} differs from the frozen configuration")
        else:
            save_json(config_path, {**BASE, "reranking": parameters})
        report = ROOT / name
        print(f"RUN {name}", flush=True)
        metrics = run(output=report, history=history, ranking_config=config_path)
        manifest = load(report / "manifest.json")
        if manifest["inputs_sha256"] != control_manifest["inputs_sha256"]:
            raise ValueError("Treatment changed structured inputs")
        experiment = f"{name}__clause_tasks_v1"
        summary["metrics"][experiment] = metrics
        summary["diagnostics"][experiment] = reranker_diagnostics(control_rows, load(report / "per_profile.json"))
        summary["latency"][experiment] = load(report / "latency.json")
        summary["sentences"][parameters["text_policy"]["preference"]] = sentence_diagnostics(inputs, parameters["text_policy"])
        comparisons = [("weighted_dot_product", control)]
        label, directory = COUNTERPARTS[name]
        if directory.is_dir():
            comparisons.append((label, directory))
        for control_label, directory in comparisons:
            result, diffs = paired_comparison(directory, report)
            stem = control_label.replace("/", "_")
            save_json(report / f"comparison_vs_{stem}.json", result)
            save_json(report / f"paired_diffs_vs_{stem}.json", diffs)
            summary["comparisons"].append({"treatment": experiment, "control": control_label, "summary": result})
        template = next(r for r in old if r["experiment"] == f"{name.removesuffix('_signed')}__context_tasks_v1")
        summary["rows"].append({**template, "experiment": experiment,
            "semantic_aggregation": "max_task_mean_sentence" + ("_signed" if name.endswith("signed") else ""),
            **{k: metrics[k] for k in METRICS}, "profile_count": metrics["profile_count"],
            "evaluator_version": manifest["evaluator_version"], "metric_extension": "", "run_id": manifest["run_id"],
            "inputs_sha256": manifest["inputs_sha256"], "dataset_fingerprint": dataset_fingerprint(manifest["dataset_sha256"]),
            "report_path": report.as_posix()})
        print(json.dumps({"experiment": experiment, **{k: round(metrics[k], 6) for k in METRICS}}), flush=True)

    if not args.no_csv:
        if CSV_PATH.read_bytes() != original:
            raise ValueError("CSV changed during experiment")
        (ROOT / "semantic_experiments_consolidated.before.csv").write_bytes(original)
        with CSV_PATH.open("a", newline="", encoding="utf-8") as handle:
            csv.DictWriter(handle, fieldnames=fields).writerows(summary["rows"])
    summary["original_csv_sha256"] = hashlib.sha256(original).hexdigest()
    summary["csv_appended"] = not args.no_csv
    summary["split"] = "development only; held-out profile files never loaded"
    write_report(summary)
    save_json(ROOT / "run_summary.json", summary)
    print(f"Report: {ROOT / 'README.md'}")


if __name__ == "__main__":
    main()
