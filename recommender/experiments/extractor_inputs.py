"""Dot product vs cosine when RIASEC comes from the real extractor instead of hidden slots.

Usage (repository root), after ``python scripts/build_extractor_sessions.py``:
    python -m recommender.experiments.extractor_inputs

Hypothesis (fixed before running): cosine's large oracle advantage (Hit@5 .683 vs
.167 on 120 profiles) partly reflects benchmark construction, because oracle and
mock-tracker vectors are the target's z-row plus noise. With vectors inferred
from profile text, cosine should still beat the dot product, by a smaller margin.

Four runs share the unchanged evaluator, pool and labels: oracle dot, oracle
cosine (references only; different input mode, never paired with tracker runs),
extractor dot and extractor cosine (the paired comparison). Extraction quality is
measured separately against hidden slots so upstream and ranking errors can be
told apart. Hidden slots never reach a ranker.
"""
import argparse
import json
import math
from pathlib import Path
import statistics

from .compare import paired_comparison
from .evaluate import digest, run, save_json
from .evaluation import METRICS

TYPES = "RIASEC"
SESSIONS = Path("data/eval/extractor_sessions_dev_v1")
ROOT = Path("reports/ranking/extractor_inputs_v1")
DOT = Path("configs/ranking/baseline_v1.json")
COSINE = Path("configs/ranking/m1_cosine.json")
RUNS = {"oracle_dot": ("oracle", DOT), "oracle_cosine": ("oracle", COSINE),
        "extractor_dot": ("actual_tracker", DOT), "extractor_cosine": ("actual_tracker", COSINE)}


def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def lines(path):
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line.strip()]


def pearson(xs, ys):
    if len(xs) < 3:
        return None
    mx, my = statistics.mean(xs), statistics.mean(ys)
    sx = math.sqrt(sum((x - mx) ** 2 for x in xs))
    sy = math.sqrt(sum((y - my) ** 2 for y in ys))
    return sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / (sx * sy) if sx and sy else None


def extraction_diagnostics(readings, profiles, *, salient=0.5):
    """Compare extracted snapshots with hidden slots (evaluation-side only)."""
    hidden = {p["id"]: p["hidden_slots"] for p in profiles}
    per_type, cosines, top_agree, counts = {t: {"observed": 0, "agree": 0, "salient": 0, "pairs": []} for t in TYPES}, [], 0, []
    for row in readings:
        truth, observed = hidden[row["id"]], row["observed_types"]
        counts.append(len(observed))
        for t in observed:
            stats, value = per_type[t], row["interests"][t]
            stats["observed"] += 1
            stats["pairs"].append((value, truth[t]))
            if abs(truth[t]) >= salient:
                stats["salient"] += 1
                stats["agree"] += (value > 0) == (truth[t] > 0)
        if observed:
            a = [row["interests"][t] for t in observed]
            b = [truth[t] for t in observed]
            na, nb = math.sqrt(sum(x * x for x in a)), math.sqrt(sum(x * x for x in b))
            if na and nb:
                cosines.append(sum(x * y for x, y in zip(a, b)) / (na * nb))
            top_agree += max(observed, key=lambda t: row["interests"][t]) == max(TYPES, key=lambda t: truth[t])
    n = len(readings)
    return {
        "profiles": n, "mean_observed_types": statistics.mean(counts),
        "profiles_with_no_observed_type": sum(c == 0 for c in counts),
        "observed_type_count_histogram": {str(k): counts.count(k) for k in range(7)},
        "top_type_agreement": top_agree / n,
        "mean_cosine_extracted_vs_hidden_on_observed": statistics.mean(cosines) if cosines else None,
        "per_type": {t: {"observed_rate": s["observed"] / n,
                         "sign_agreement_when_hidden_abs_ge_0_5": s["agree"] / s["salient"] if s["salient"] else None,
                         "pearson_extracted_vs_hidden": pearson(*zip(*s["pairs"])) if len(s["pairs"]) >= 3 else None}
                     for t, s in per_type.items()},
        "definition": f"Observed = extractor produced a non-neutral slot. Salient = |hidden_slots| >= {salient}. "
                      "Top-type agreement: highest extracted observed type equals highest hidden type.",
    }


def write_report(summary):
    rows = ["| Run | input | " + " | ".join(METRICS) + " |", "|---|---|" + "---:|" * len(METRICS)]
    for name, item in summary["metrics"].items():
        rows.append(f"| {name} | {RUNS[name][0]} | " + " | ".join(f"{item[m]:.6f}" for m in METRICS) + " |")
    lines_ = ["# Extractor-derived inputs: dot product vs cosine, v1", "",
              "Generated by `python -m recommender.experiments.extractor_inputs` from saved artifacts.", "",
              "## Hypothesis", "", summary["hypothesis"], "", "## Ten permanent M2 metrics (120 development profiles)", "",
              *rows, "", "Oracle rows are references built from hidden slots; they are not paired with tracker rows.", "",
              "## Paired comparisons (treatment minus control, 95% bootstrap CI)", "",
              "| Comparison | Hit@5 | MRR | NDCG@10 | Recall@10 | improved / regressed (MRR) |", "|---|---:|---:|---:|---:|---:|"]
    for label, result in summary["comparisons"].items():
        m = result["metrics"]
        cell = lambda k: f"{m[k]['mean_difference']:+.6f} [{m[k]['ci95'][0]:+.6f}, {m[k]['ci95'][1]:+.6f}]"
        lines_.append(f"| {label} | {cell('hit_at_5')} | {cell('mrr')} | {cell('ndcg_at_10')} | {cell('recall_at_10')} | "
                      f"{m['mrr']['improved']} / {m['mrr']['regressed']} |")
    d = summary["extraction"]
    lines_ += ["", "## Extraction quality (evaluation-side, against hidden slots)", "",
               f"- Mean observed RIASEC types per profile: {d['mean_observed_types']:.2f}; "
               f"profiles with none: {d['profiles_with_no_observed_type']}",
               f"- Observed-type count histogram: {json.dumps(d['observed_type_count_histogram'])}",
               f"- Top-type agreement: {d['top_type_agreement']:.3f}",
               f"- Mean cosine of extracted vs hidden (observed types): {d['mean_cosine_extracted_vs_hidden_on_observed']:.3f}", "",
               "| Type | observed rate | sign agreement (|hidden| >= .5) | Pearson r |", "|---|---:|---:|---:|"]
    fmt = lambda v: "n/a" if v is None else f"{v:.3f}"
    for t, s in d["per_type"].items():
        lines_.append(f"| {t} | {fmt(s['observed_rate'])} | {fmt(s['sign_agreement_when_hidden_abs_ge_0_5'])} | "
                      f"{fmt(s['pearson_extracted_vs_hidden'])} |")
    lines_ += ["", "## Limitations", "",
               "- One opening turn per profile; no clarifying questions, probing or contradiction handling.",
               "- Profile text is LLM-written from hidden slots (reported r = .89 full, .78 messy), so it is still synthetic.",
               "- Exact-target metrics penalise reasonable neighbours; read NDCG/Recall alongside Hit/MRR.",
               "- Development data only; defaults unchanged.", ""]
    (ROOT / "README.md").write_text("\n".join(lines_), encoding="utf-8")


def main():
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    if (ROOT / "run_summary.json").exists():
        raise ValueError(f"{ROOT} already holds a completed experiment; choose a new version")
    sessions_manifest = load(SESSIONS / "manifest.json")
    for name, expected in sessions_manifest["outputs_sha256"].items():
        if digest(SESSIONS / name) != expected:
            raise ValueError(f"Session file changed after building: {name}")
    ROOT.mkdir(parents=True, exist_ok=True)
    base = load("configs/m2.json")
    configs = {"oracle": Path("configs/m2.json")}
    tracker_config = ROOT / "evaluation_actual_tracker.json"
    if not tracker_config.exists():
        save_json(tracker_config, {**base, "run_id": "m2_extractor_tracker_dev_v1", "input_mode": "actual_tracker",
                                   "profiles": (SESSIONS / "sessions.jsonl").as_posix()})
    configs["actual_tracker"] = tracker_config
    history = ROOT / "evaluation_history.csv"
    summary = {"hypothesis": " ".join(__doc__.split("\n\n")[2:4]).replace("\n", " "),
               "sessions_manifest": sessions_manifest, "metrics": {}, "comparisons": {}}
    for name, (mode, ranking) in RUNS.items():
        print(f"RUN {name}", flush=True)
        summary["metrics"][name] = run(configs[mode], ROOT / name, history=history, ranking_config=ranking)
    for label, (control, treatment) in {"extractor: cosine - dot": ("extractor_dot", "extractor_cosine"),
                                        "oracle: cosine - dot (reference)": ("oracle_dot", "oracle_cosine")}.items():
        result, diffs = paired_comparison(ROOT / control, ROOT / treatment)
        save_json(ROOT / f"comparison_{treatment}_vs_{control}.json", result)
        save_json(ROOT / f"paired_diffs_{treatment}_vs_{control}.json", diffs)
        summary["comparisons"][label] = result
    summary["extraction"] = extraction_diagnostics(lines(SESSIONS / "readings.jsonl"), lines("data/dev_profiles.jsonl"))
    write_report(summary)
    save_json(ROOT / "run_summary.json", summary)
    print(json.dumps({name: {m: round(v[m], 6) for m in ("hit_at_5", "mrr", "ndcg_at_10")}
                      for name, v in summary["metrics"].items()}, indent=2))
    print(f"Report: {ROOT / 'README.md'}")


if __name__ == "__main__":
    main()
