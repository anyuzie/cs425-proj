"""Familiarity-aware profile policies on extractor-derived inputs.

Usage (repository root):
    python -m recommender.experiments.familiarity_policy

Two policies from recommender/profile_policy.py
(``familiarity_excluded_v1``, ``familiarity_half_v1``) are each applied in front of
the dot product and cosine, and compared with the same scorer on the
raw tracker vector. Primary metric: MRR; NDCG@10 secondary. Subgroups use hidden
slots on the evaluation side only, to separate profiles whose familiarity slots
are misleading (sign contradicts hidden) from those where they are genuine.
"""
import argparse
import json
from pathlib import Path
import statistics

from .compare import paired_comparison
from .evaluate import digest, run, save_json
from .evaluation import METRICS

SESSIONS = Path("data/eval/extractor_sessions_dev_v2")
ROOT = Path("reports/ranking/familiarity_policy_v1")
SCORERS = {"dot": {"m1": {"algorithm": "weighted_dot_product", "variant": "baseline_v1"}, "fusion": {"algorithm": "rrf", "k": 60}},
           "cosine": {"m1": {"algorithm": "cosine_similarity", "variant": "baseline_v1"}, "fusion": None}}
POLICIES = ("raw", "familiarity_excluded_v1", "familiarity_half_v1")
PRIMARY = ("mrr", "ndcg_at_10", "hit_at_5", "recall_at_10")


def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def lines(path):
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line.strip()]


def config(scorer, policy):
    selection = SCORERS[scorer]
    value = {"components": {"m1": selection["m1"], "m3": None, "m4": None}, "fusion": selection["fusion"]}
    return value if policy == "raw" else {**value, "profile_policy": policy}


def subgroups(sessions, profiles):
    """Evaluation-side strata: none / genuine-only / misleading-present familiarity."""
    hidden = {p["id"]: p["hidden_slots"] for p in profiles}
    groups = {}
    for session in sessions:
        turn = session["turns"][-1]
        familiar = [t for t, reason in turn["slot_reasons"].items() if reason == "familiarity"]
        if not familiar:
            groups[session["id"]] = "no_familiarity"
        elif any(turn["interests"][t] * hidden[session["id"]][t] < 0 for t in familiar):
            groups[session["id"]] = "misleading_present"
        else:
            groups[session["id"]] = "genuine_only"
    return groups


def subgroup_effects(diffs, groups):
    result = {}
    for name in ("no_familiarity", "genuine_only", "misleading_present"):
        rows = [d for d in diffs if groups[d["profile_id"]] == name]
        result[name] = {"profiles": len(rows), **{m: statistics.mean(r[m] for r in rows) if rows else None
                                                  for m in ("mrr", "ndcg_at_10", "hit_at_5")}}
    return result


def write_report(summary):
    out = ["# Familiarity-aware profile policies, v1", "",
           "Generated by `python -m recommender.experiments.familiarity_policy` from saved artifacts.", "",
           "## Hypothesis", "", summary["hypothesis"], "",
           "## Ten permanent M2 metrics (120 development profiles, extractor-derived single-turn inputs)", "",
           "| Run | no-signal profiles | " + " | ".join(METRICS) + " |", "|---|---:|" + "---:|" * len(METRICS)]
    for name, item in summary["metrics"].items():
        out.append(f"| {name} | {summary['no_signal'][name]} | " + " | ".join(f"{item[m]:.6f}" for m in METRICS) + " |")
    out += ["", "## Paired differences versus the same scorer on the raw vector (95% bootstrap CI)", "",
            "| Treatment | " + " | ".join(PRIMARY) + " | improved / regressed (MRR) |", "|---|" + "---:|" * (len(PRIMARY) + 1)]
    for name, result in summary["comparisons"].items():
        m = result["metrics"]
        cells = [f"{m[k]['mean_difference']:+.6f} [{m[k]['ci95'][0]:+.6f}, {m[k]['ci95'][1]:+.6f}]" for k in PRIMARY]
        out.append(f"| {name} | " + " | ".join(cells) + f" | {m['mrr']['improved']} / {m['mrr']['regressed']} |")
    counts = summary["subgroup_counts"]
    out += ["", "## Subgroups (evaluation-side, from hidden slots)", "",
            f"Profiles: no familiarity slot {counts['no_familiarity']}, familiarity all genuine {counts['genuine_only']}, "
            f"at least one misleading familiarity slot {counts['misleading_present']}. Mean treatment-minus-raw differences:", "",
            "| Treatment | subgroup | n | MRR | NDCG@10 | Hit@5 |", "|---|---|---:|---:|---:|---:|"]
    for name, groups in summary["subgroups"].items():
        for group, values in groups.items():
            if group == "no_familiarity":
                continue
            fmt = lambda v: "n/a" if v is None else f"{v:+.6f}"
            out.append(f"| {name} | {group} | {values['profiles']} | {fmt(values['mrr'])} | "
                       f"{fmt(values['ndcg_at_10'])} | {fmt(values['hit_at_5'])} |")
    out += ["", "Profiles without familiarity slots are unchanged by construction (difference 0).", "",
            "## Limitations", "",
            "- One opening turn; the extractor's reason label is unverified against human judgement.",
            "- Subgroups are defined with hidden slots, which a live system cannot see; they explain effects, they do not select them.",
            "- 120 synthetic development profiles; the CIs describe this set only. Defaults unchanged.", ""]
    (ROOT / "README.md").write_text("\n".join(out), encoding="utf-8")


def main():
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    if (ROOT / "run_summary.json").exists():
        raise ValueError(f"{ROOT} already holds a completed experiment; choose a new version")
    manifest = load(SESSIONS / "manifest.json")
    for name, expected in manifest["outputs_sha256"].items():
        if digest(SESSIONS / name) != expected:
            raise ValueError(f"Session file changed after building: {name}")
    ROOT.mkdir(parents=True, exist_ok=True)
    evaluation = ROOT / "evaluation_actual_tracker.json"
    if not evaluation.exists():
        save_json(evaluation, {**load("configs/m2.json"), "run_id": "m2_extractor_tracker_dev_v2",
                               "input_mode": "actual_tracker", "profiles": (SESSIONS / "sessions.jsonl").as_posix()})
    history = ROOT / "evaluation_history.csv"
    sessions, profiles = lines(SESSIONS / "sessions.jsonl"), lines("data/dev_profiles.jsonl")
    groups = subgroups(sessions, profiles)
    summary = {"hypothesis": " ".join(__doc__.split("\n\n")[2:3]).replace("\n", " "),
               "sessions_manifest": manifest, "metrics": {}, "no_signal": {}, "comparisons": {}, "subgroups": {},
               "subgroup_counts": {g: list(groups.values()).count(g) for g in ("no_familiarity", "genuine_only", "misleading_present")}}
    for scorer in SCORERS:
        for policy in POLICIES:
            name = f"{scorer}_{policy}"
            path = Path("configs/ranking") / f"profile_{policy}_{scorer}.json"
            if policy != "raw":
                if path.exists() and load(path) != config(scorer, policy):
                    raise ValueError(f"{path} differs from the frozen configuration")
                if not path.exists():
                    save_json(path, config(scorer, policy))
            print(f"RUN {name}", flush=True)
            summary["metrics"][name] = run(evaluation, ROOT / name, history=history,
                                           ranking_config=path if policy != "raw" else config(scorer, policy))
            summary["no_signal"][name] = sum(r["status"] != "ranked" for r in load(ROOT / name / "per_profile.json"))
            if policy != "raw":
                result, diffs = paired_comparison(ROOT / f"{scorer}_raw", ROOT / name)
                save_json(ROOT / f"comparison_{name}_vs_raw.json", result)
                save_json(ROOT / f"paired_diffs_{name}_vs_raw.json", diffs)
                summary["comparisons"][name] = result
                summary["subgroups"][name] = subgroup_effects(diffs, groups)
    reference = load("reports/ranking/extractor_inputs_v1/run_summary.json")["metrics"]
    for scorer in SCORERS:
        if any(abs(summary["metrics"][f"{scorer}_raw"][m] - reference[f"extractor_{scorer}"][m]) > 1e-12 for m in METRICS):
            raise ValueError(f"{scorer} raw control no longer reproduces extractor_inputs_v1")
    summary["controls_reproduce_extractor_inputs_v1"] = True
    write_report(summary)
    save_json(ROOT / "run_summary.json", summary)
    print(json.dumps({n: {m: round(v[m], 6) for m in ("mrr", "ndcg_at_10", "hit_at_5")} for n, v in summary["metrics"].items()}, indent=2))
    print(f"Report: {ROOT / 'README.md'}")


if __name__ == "__main__":
    main()
